import { jsPDF } from 'jspdf';
import type { Payment, Student } from '@/types';
import { school } from '@/data/school';
import { fmtDate } from './format';

const NAVY: [number, number, number] = [11, 26, 51];
const GOLD: [number, number, number] = [194, 146, 52];
// jsPDF core fonts don't include ₹ – use "Rs."
const rs = (n: number) => `Rs. ${new Intl.NumberFormat('en-IN').format(n)}`;

function header(doc: jsPDF, title: string) {
  const w = doc.internal.pageSize.getWidth();
  doc.setFillColor(...NAVY); doc.rect(0, 0, w, 34, 'F');
  doc.setFillColor(...GOLD); doc.rect(0, 34, w, 1.5, 'F');
  doc.setTextColor(255, 255, 255); doc.setFont('times', 'bold'); doc.setFontSize(18);
  doc.text(school.name, 14, 15);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9);
  doc.text(`${school.town}, ${school.state}  |  ${school.email}`, 14, 22);
  doc.setFont('helvetica', 'bold'); doc.setFontSize(11);
  doc.text(title.toUpperCase(), w - 14, 15, { align: 'right' });
  doc.setTextColor(...NAVY);
}

function footer(doc: jsPDF) {
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();
  doc.setFontSize(8); doc.setTextColor(120, 130, 150);
  doc.text('DEMO DOCUMENT – generated by the school portal prototype. Not valid for official use.', w / 2, h - 10, { align: 'center' });
}

export function downloadReceipt(p: Payment, student: Student, className: string) {
  const doc = new jsPDF({ unit: 'mm', format: 'a5' });
  header(doc, 'Fee Receipt');
  const w = doc.internal.pageSize.getWidth();
  doc.setFontSize(10); doc.setFont('helvetica', 'normal');
  const rows: [string, string][] = [
    ['Receipt No.', p.receiptNo], ['Date', fmtDate(p.date)], ['Student', student.name],
    ['Admission No.', student.admissionNo], ['Class', `${className} – ${student.section}`], ['Father\'s Name', student.fatherName],
    ['Instalment', p.installment], ['Payment Mode', p.method], ['Transaction ID', p.txnId],
  ];
  let y = 48;
  rows.forEach(([k, v]) => {
    doc.setTextColor(110, 120, 140); doc.text(k, 14, y);
    doc.setTextColor(...NAVY); doc.text(String(v), 60, y);
    y += 7.5;
  });
  y += 2;
  doc.setDrawColor(220, 225, 235); doc.line(14, y, w - 14, y); y += 10;
  doc.setFont('helvetica', 'bold'); doc.setFontSize(12);
  doc.text('Amount Paid', 14, y); doc.text(rs(p.amount), w - 14, y, { align: 'right' });
  y += 8; doc.setFont('helvetica', 'normal'); doc.setFontSize(9);
  doc.setTextColor(22, 128, 61); doc.text(`Status: ${p.status.toUpperCase()}`, 14, y);
  doc.setTextColor(...NAVY); doc.text('Authorised Signatory (Accounts)', w - 14, y + 18, { align: 'right' });
  footer(doc);
  doc.save(`Receipt-${p.receiptNo.replace(/\//g, '-')}.pdf`);
}

export function downloadAdmissionForm() {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  header(doc, `Admission Form ${school.academicYear}`);
  const w = doc.internal.pageSize.getWidth();
  doc.setFontSize(10); doc.setFont('helvetica', 'normal');
  const fields = [
    'Name of the Student', 'Date of Birth', 'Gender', 'Class applied for', 'Previous School (if any)', "Father's Name",
    "Father's Occupation", "Mother's Name", "Mother's Occupation", 'Residential Address', '', 'Mobile Number', 'Email Address',
    'Aadhaar Number (Student)', 'Transport Required (Yes / No)', 'Pick-up Point',
  ];
  let y = 52;
  fields.forEach((f) => {
    doc.setTextColor(...NAVY); doc.text(f, 14, y);
    doc.setDrawColor(190, 200, 215); doc.line(75, y + 1, w - 14, y + 1);
    y += 11;
  });
  y += 4;
  doc.setFont('helvetica', 'bold'); doc.text('Documents to attach', 14, y); y += 7; doc.setFont('helvetica', 'normal');
  ['Birth certificate', 'Passport-size photographs (4)', 'Aadhaar card of student and parents', 'Transfer certificate & report card of previous class (Class 2 onwards)', 'Address proof'].forEach((d) => {
    doc.rect(14, y - 3.5, 3.5, 3.5); doc.text(d, 21, y); y += 7;
  });
  y += 10;
  doc.text('Signature of Parent / Guardian', 14, y); doc.text('Date', w - 50, y);
  footer(doc);
  doc.save('SPS-Admission-Form.pdf');
}

/** Generic one-page document used for demo circulars / study notes downloads. */
export function downloadDemoDocument(title: string, lines: string[], fileName: string) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  header(doc, 'Document');
  doc.setFont('times', 'bold'); doc.setFontSize(16); doc.text(title, 14, 52, { maxWidth: 180 });
  doc.setFont('helvetica', 'normal'); doc.setFontSize(11);
  let y = 66;
  lines.forEach((l) => { const split = doc.splitTextToSize(l, 180); doc.text(split, 14, y); y += split.length * 6 + 4; });
  footer(doc);
  doc.save(fileName.endsWith('.pdf') ? fileName : `${fileName}.pdf`);
}

export function downloadReportPdf(title: string, head: string[], body: (string | number)[][], fileName: string) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4', orientation: head.length > 6 ? 'landscape' : 'portrait' });
  header(doc, 'Report');
  const w = doc.internal.pageSize.getWidth();
  doc.setFont('times', 'bold'); doc.setFontSize(14); doc.text(title, 14, 48);
  const colW = (w - 28) / head.length;
  let y = 58;
  const drawHead = () => {
    doc.setFillColor(238, 242, 248); doc.rect(14, y - 5, w - 28, 8, 'F');
    doc.setFont('helvetica', 'bold'); doc.setFontSize(8.5);
    head.forEach((h, i) => doc.text(h, 16 + i * colW, y));
    y += 8; doc.setFont('helvetica', 'normal');
  };
  drawHead();
  body.forEach((row) => {
    if (y > doc.internal.pageSize.getHeight() - 20) { footer(doc); doc.addPage(); header(doc, 'Report'); y = 48; drawHead(); }
    row.forEach((c, i) => doc.text(String(c).slice(0, 34), 16 + i * colW, y));
    y += 7;
  });
  footer(doc);
  doc.save(fileName);
}
