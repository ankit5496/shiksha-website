/** Current teacher record for the logged-in teacher. */
export function useTeacher() {
  const { user } = useAuth();
  const { items, loading } = useCollection('teachers');
  const teacher = items.find((t) => t.id === user?.teacherId);
  return { teacher, loading };
}

/** "c8-A" → { classId: 'c8', section: 'A' } */
export const splitCS = (cs: string) => { const i = cs.lastIndexOf('-'); return { classId: cs.slice(0, i), section: cs.slice(i + 1) }; };

export function useClassSectionLabel() {
  const { items: classes } = useCollection('classes');
  return (cs: string) => { const { classId, section } = splitCS(cs); return `${classes.find((c) => c.id === classId)?.name ?? classId} – ${section}`; };
}

const SUBJECT_STYLE: Record<string, { icon: typeof BookOpen; cls: string }> = {
  Science: { icon: FlaskConical, cls: 'bg-emerald-50 text-emerald-700' },
  Mathematics: { icon: Calculator, cls: 'bg-sky-50 text-sky-700' },
  English: { icon: BookOpen, cls: 'bg-navy-50 text-navy-700' },
  Hindi: { icon: Languages, cls: 'bg-orange-50 text-orange-700' },
  Sanskrit: { icon: Languages, cls: 'bg-amber-50 text-amber-700' },
  'Social Science': { icon: Globe2, cls: 'bg-teal-50 text-teal-700' },
  Computer: { icon: Monitor, cls: 'bg-indigo-50 text-indigo-700' },
  'Information Technology': { icon: Monitor, cls: 'bg-indigo-50 text-indigo-700' },
  Art: { icon: Palette, cls: 'bg-pink-50 text-pink-700' },
};
export function SubjectIcon({ subject, size = 'md' }: { subject: string; size?: 'sm' | 'md' }) {
  const s = SUBJECT_STYLE[subject] ?? { icon: BookOpen, cls: 'bg-gold-50 text-gold-700' };
  const I = s.icon;
  return <div className={clsx('flex shrink-0 items-center justify-center rounded-xl', s.cls, size === 'sm' ? 'h-9 w-9' : 'h-11 w-11')}><I className={size === 'sm' ? 'h-4 w-4' : 'h-5 w-5'} /></div>;
}

export const CATEGORY_LABEL: Record<StudyMaterial['category'], string> = { notes: 'Notes', 'exam-prep': 'Exam Prep', resource: 'Resource', video: 'Video' };
export const categoryTone = (c: StudyMaterial['category']): Tone => ({ notes: 'navy', 'exam-prep': 'gold', resource: 'blue', video: 'green' } as const)[c];

export function openMaterial(m: StudyMaterial) {
  if (m.url && m.category !== 'video') { window.open(m.url, '_blank', 'noopener'); return; }
  downloadDemoDocument(m.title, [
    `Subject: ${m.subject}`, `Uploaded by: ${m.uploadedBy} on ${fmtDate(m.date)}`, '', m.description,
    'This is a demonstration document generated by the LMS prototype. In production, the original file uploaded by the teacher (stored on Cloudinary) is downloaded here.',
  ], m.fileName ?? m.title.replace(/\W+/g, '-').toLowerCase());
}

