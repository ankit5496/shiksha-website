export type AssignmentState = 'Pending' | 'Overdue' | 'Submitted' | 'Late' | 'Graded';
export function assignmentState(a: Assignment, sub?: Submission): AssignmentState {
  if (sub) return sub.status;
  return a.dueDate < todayISO() ? 'Overdue' : 'Pending';
}
export const stateTone = (s: AssignmentState): Tone => ({ Pending: 'amber', Overdue: 'red', Submitted: 'blue', Late: 'amber', Graded: 'green' } as const)[s];

/** Assignments + submissions for the logged-in student. */
export function useStudentAssignments(classId?: string, section?: string, studentId?: string) {
  const a = useCollection('assignments');
  const s = useCollection('submissions');
  const list = useMemo(() => a.items
    .filter((x) => x.classId === classId && x.section === section)
    .map((x) => { const sub = s.items.find((y) => y.assignmentId === x.id && y.studentId === studentId); return { a: x, sub, state: assignmentState(x, sub) }; })
    .sort((p, q) => p.a.dueDate.localeCompare(q.a.dueDate)), [a.items, s.items, classId, section, studentId]);
  return { list, loading: a.loading || s.loading, submissions: s };
}

